defmodule ExHdl.ML.QuantizedTest do
  @moduledoc """
  int8 fully connected layer with TFLite semantics: reference values worked
  out from the TFLite/gemmlowp sources, bit-identity between the Nx
  evaluator and code generated by ExHdl.SIMD.Compiler, and accuracy against
  a float reference.
  """
  use ExUnit.Case, async: true
  use ExUnitProperties

  import Nx.Defn
  alias ExHdl.ML.Quantized, as: Q

  @moduletag timeout: 600_000

  defn mbqm(acc, opts \\ []) do
    opts = keyword!(opts, [:multiplier, :shift])
    Q.multiply_by_quantized_multiplier(acc, opts[:multiplier], opts[:shift])
  end

  defp simd(fun), do: Nx.Defn.jit(fun, compiler: ExHdl.SIMD.Compiler, fallback: false)

  describe "requantization (TFLite reference values)" do
    test "QuantizeMultiplier" do
      assert Q.quantize_multiplier(0.09375) == {1_610_612_736, -3}
      assert Q.quantize_multiplier(0.5) == {1_073_741_824, 0}
      assert Q.quantize_multiplier(0.0) == {0, 0}
    end

    test "MultiplyByQuantizedMultiplier rounds twice, ties away from zero" do
      # acc * 0.09375: -184.5 -> -185 (single rounding would give -184),
      # -186.47 -> -187 (double-rounding artefact), 203.06 -> 203.
      acc = Nx.tensor([-1968, -1989, 2166, 0, 1, -334], type: :s32)
      expected = [-185, -187, 203, 0, 0, -31]

      for run <- [&mbqm/2, simd(&mbqm/2)] do
        assert run.(acc, multiplier: 1_610_612_736, shift: -3) |> Nx.to_list() == expected
      end
    end
  end

  describe "fully_connected" do
    @worked [
      weights: [[3, -7, 2, -1]],
      bias: [-1500],
      input_scale: 0.5,
      input_zero_point: -3,
      weight_scales: 0.375,
      output_scale: 2.0,
      output_zero_point: -10
    ]

    test "worked example: -41, or -10 with ReLU" do
      x = Nx.tensor([[10, -128, 127, 5]], type: :s8)

      for {activation, expected} <- [none: -41, relu: -10],
          run <- [&Q.fully_connected/2, simd(&Q.fully_connected/2)] do
        params = Q.fully_connected_params(@worked ++ [activation: activation])
        assert run.(x, params) |> Nx.to_flat_list() == [expected]
      end
    end

    property "SIMD-generated code is bit-identical to the evaluator and within 1 LSB of float" do
      check all batch <- integer(1..6),
                inputs <- integer(1..48),
                outputs <- integer(1..12),
                weights <- list_of(list_of(integer(-127..127), length: inputs), length: outputs),
                bias <- list_of(integer(-30_000..30_000), length: outputs),
                x <- list_of(list_of(integer(-128..127), length: inputs), length: batch),
                in_zp <- integer(-128..127),
                out_zp <- integer(-128..127),
                input_scale <- float(min: 0.01, max: 0.1),
                weight_scales <- list_of(float(min: 0.001, max: 0.02), length: outputs),
                output_scale <- float(min: 0.05, max: 0.5),
                activation <- member_of([:none, :relu]),
                max_runs: 15 do
        params =
          Q.fully_connected_params(
            weights: weights,
            bias: bias,
            input_scale: input_scale,
            input_zero_point: in_zp,
            weight_scales: weight_scales,
            output_scale: output_scale,
            output_zero_point: out_zp,
            activation: activation
          )

        xt = Nx.tensor(x, type: :s8)
        ref = Q.fully_connected(xt, params) |> Nx.to_list()
        assert simd(&Q.fully_connected/2).(xt, params) |> Nx.to_list() == ref

        # float reference: same math with real scales, rounded and clamped once
        for {row, out_row} <- Enum.zip(x, ref),
            {w_row, b, ws, q} <- Enum.zip([weights, bias, weight_scales, out_row]) do
          acc = Enum.zip_with(row, w_row, fn xv, wv -> (xv - in_zp) * wv end) |> Enum.sum()
          real = out_zp + (acc + b) * input_scale * ws / output_scale
          exact = real |> round() |> max(params[:activation_min]) |> min(params[:activation_max])
          assert abs(q - exact) <= 1, "float #{real} -> #{exact}, int8 #{q}"
        end
      end
    end
  end
end
